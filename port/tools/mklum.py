"""Generate platform/fz_lumcolormap.c from the WAD's COLORMAP and PLAYPAL.

The engine looks every pixel up in fullcolormap[light * 256 + palette index].
On Flipper the result is not a palette index but a 6-bit luminance with the
tone curve from the dithering lab baked in (Doom is dark: lift the shadows,
clip the highlights). The table is const, so it lives in flash.

usage: mklum.py DOOM8088.WAD platform/fz_lumcolormap.c
"""
import struct
import sys

GAMMA, BLACK, WHITE = 0.55, 0.02, 0.75


def lumps(path):
    data = open(path, "rb").read()
    n, off = struct.unpack("<ii", data[4:12])
    out = {}
    for i in range(n):
        pos, size, name = struct.unpack("<ii8s", data[off + i * 16: off + i * 16 + 16])
        out[name.rstrip(b"\0").decode()] = data[pos:pos + size]
    return out


def tone(l):
    l = min(max((l - BLACK) / (WHITE - BLACK), 0.0), 1.0)
    return l ** GAMMA


def main(wad, out_path):
    l = lumps(wad)
    pal = l["PLAYPAL"][:768]
    cmap = l["COLORMAP"]
    maps = len(cmap) // 256
    assert maps == 34, maps

    lum = []
    for i in range(256):
        r, g, b = pal[i * 3: i * 3 + 3]
        lum.append(round(tone((0.299 * r + 0.587 * g + 0.114 * b) / 255) * 63))

    rows = []
    for m in range(maps):
        row = [lum[cmap[m * 256 + i]] for i in range(256)]
        rows.append("\t" + ",".join(str(v) for v in row) + ",")

    with open(out_path, "w", newline="\n") as f:
        f.write("// Generated by tools/mklum.py from DOOM8088.WAD: do not edit.\n")
        f.write("// fullcolormap[light * 256 + palette index] = 6-bit luminance\n")
        f.write(f"// tone curve: gamma {GAMMA}, black {BLACK}, white {WHITE}\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"const uint8_t fullcolormap[256 * {maps}] =\n{{\n")
        f.write("\n".join(rows))
        f.write("\n};\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
