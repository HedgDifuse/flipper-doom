"""Doom-style graphics for the loader's screens, from doom1.wad.

  python port/tools/mkui.py wad/doom1.wad port/flipper/fap/ui_assets.h [preview_dir]

The logo (M_DOOM) as 4-bit brightness at two sizes goes to files/ui.bin next
to the header (read from the SD card while drawn: what a FAP holds takes RAM
from the game); the menu font (STCFN*, 1-bit) and the skull cursor
(M_SKULL1/2) go into the header. With preview_dir: PNGs of the splash and the
menu as the LCD's grays would show them.
"""
import struct, sys
from PIL import Image

wad = open(sys.argv[1], 'rb').read()
n, off = struct.unpack('<ii', wad[4:12])
lumps = {}
for i in range(n):
    p, s, name = struct.unpack('<ii8s', wad[off + 16 * i: off + 16 * i + 16])
    lumps[name.rstrip(b'\0').decode()] = wad[p:p + s]
pal = lumps['PLAYPAL'][:768]


def patch(name):
    """RGBA image of a patch (transparent where no post)."""
    d = lumps[name]
    w, h, _, _ = struct.unpack('<hhhh', d[:8])
    img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    px = img.load()
    for x in range(w):
        p = struct.unpack('<I', d[8 + 4 * x: 12 + 4 * x])[0]
        while d[p] != 0xff:
            top, length = d[p], d[p + 1]
            for j in range(length):
                c = d[p + 3 + j]
                px[x, top + j] = (pal[3 * c], pal[3 * c + 1], pal[3 * c + 2], 255)
            p += length + 4
    return img


def brightness(img, stretch=True):
    """0..1 brightness per pixel, None where transparent; contrast stretched."""
    w, h = img.size
    px = img.load()
    v = [[None] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            # the red logo: red counts more than true luminance would give it
            if a >= 128:
                v[y][x] = (0.6 * r + 0.3 * g + 0.1 * b) / 255
    if stretch:
        hi = max(max(c for c in r if c is not None) for r in v if any(c is not None for c in r)) or 1
        v = [[None if c is None else min(1.0, (c / hi) ** 0.55) for c in r] for r in v]
    return v


def scaled(img, w, h):
    return img.resize((w, h), Image.LANCZOS)


def nibbles(v):
    """Row by row, each row padded to whole bytes, low nibble first:
    0 transparent, 1..15 brightness 0..1."""
    out = []
    for r in v:
        flat = [0 if c is None else 1 + min(14, int(c * 14 + 0.5)) for c in r]
        if len(flat) % 2:
            flat.append(0)
        for i in range(0, len(flat), 2):
            out.append(flat[i] | flat[i + 1] << 4)
    return out


def mask_rows(img, thresh=0.22):  # the letters are 0.29-0.55, their outline 0.15
    """1-bit rows (LSB = leftmost), bytes per row = ceil(w/8)."""
    v = brightness(img, stretch=False)
    w, h = img.size
    rows = []
    for y in range(h):
        bits = 0
        for x in range(w):
            if v[y][x] is not None and v[y][x] > thresh:
                bits |= 1 << x
        rows.append(bits)
    return rows


def c_array(name, data, per_line=16):
    s = 'static const uint8_t %s[%d] = {\n' % (name, len(data))
    for i in range(0, len(data), per_line):
        s += '\t' + ', '.join('0x%02x' % b for b in data[i:i + per_line]) + ',\n'
    return s + '};\n'


out = ['// generated by port/tools/mkui.py from doom1.wad: do not edit\n#pragma once\n#include <stdint.h>\n']
logo = patch('M_DOOM')
LOGOS = {'big': (123, 60), 'small': (60, 29)}
logo_v = {}
blob = bytearray()
out.append('// in files/ui.bin: brightness 0..15, two pixels a byte (low nibble\n'
           '// first), rows padded to whole bytes\n')
for key, (w, h) in LOGOS.items():
    img = logo if (w, h) == logo.size else scaled(logo, w, h)
    v = brightness(img)
    logo_v[key] = v
    out.append('#define UI_LOGO_%s_W %d\n#define UI_LOGO_%s_H %d\n#define UI_LOGO_%s_POS %d\n'
               % (key.upper(), w, key.upper(), h, key.upper(), len(blob)))
    blob += bytes(nibbles(v))
import os
open(os.path.join(os.path.dirname(sys.argv[2]), 'files', 'ui.bin'), 'wb').write(blob)

# font: STCFN033 ('!') .. STCFN095 ('_'), 1-bit, all 7 rows high
glyphs, widths, font_h = [], [], 7
for c in range(33, 96):
    name = 'STCFN%03d' % c
    if name not in lumps:
        glyphs.append([0] * font_h); widths.append(4); continue
    g = patch(name)
    top = -struct.unpack('<h', lumps[name][6:8])[0]  # '.' and ',' sit low
    rows = [0] * top + mask_rows(g)
    rows = (rows + [0] * font_h)[:font_h]
    # the glyphs are outlined: a blank column each side; one is gap enough
    glyphs.append(rows); widths.append(g.size[0] - 1)
out.append('#define UI_FONT_H %d\n#define UI_FONT_FIRST 33\n#define UI_FONT_LAST 95\n#define UI_FONT_SPACE 4\n' % font_h)
out.append(c_array('ui_font_width', widths))
out.append('// a byte a row, LSB = leftmost pixel\n')
out.append(c_array('ui_font', [r & 0xff for g in glyphs for r in g]))

# skull cursor, scaled down to the font's height + 2
SK_W, SK_H = 10, 9  # with the outline: drawn 1 px larger than the skull
skulls = []
for name in ('M_SKULL1', 'M_SKULL2'):
    s = scaled(patch(name), SK_W, SK_H)
    v = brightness(s)
    # a dark outline: the skull is bone white, the menu's background light
    out_v = [r[:] for r in v]
    for y in range(SK_H):
        for x in range(SK_W):
            if v[y][x] is None and any(0 <= y + dy < SK_H and 0 <= x + dx < SK_W and v[y + dy][x + dx] is not None
                                       for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                out_v[y][x] = 0.0
    skulls.append(out_v)
out.append('#define UI_SKULL_W %d\n#define UI_SKULL_H %d\n' % (SK_W, SK_H))
out.append('// brightness 0..15 as the logo, two frames\n')
out.append('#define UI_SKULL_FRAME %d // bytes\n' % len(nibbles(skulls[0])))
out.append(c_array('ui_skull', nibbles(skulls[0]) + nibbles(skulls[1])))
open(sys.argv[2], 'w', newline='\n').write(''.join(out))
print('wrote', sys.argv[2])

